    /**
     * Phonetic transliteration for Devanagari characters to English ASCII.
     */
    fun transliterateDevanagariToAscii(text: String): String {
        val sb = StringBuilder()
        var i = 0
        val len = text.length
        while (i < len) {
            val ch = text[i]
            when (ch) {
                ' ' -> sb.append('_')
                'अ' -> sb.append("A")
                'आ' -> sb.append("Aa")
                'इ' -> sb.append("I")
                'ई' -> sb.append("Ee")
                'उ' -> sb.append("U")
                'ऊ' -> sb.append("Oo")
                'ऋ' -> sb.append("Ri")
                'ए' -> sb.append("E")
                'ऐ' -> sb.append("Ai")
                'ओ' -> sb.append("O")
                'औ' -> sb.append("Au")
                'क' -> sb.append(consonantWithVowel(text, i, "K"))
                'ख' -> sb.append(consonantWithVowel(text, i, "Kh"))
                'ग' -> sb.append(consonantWithVowel(text, i, "G"))
                'घ' -> sb.append(consonantWithVowel(text, i, "Gh"))
                'च' -> sb.append(consonantWithVowel(text, i, "Ch"))
                'छ' -> sb.append(consonantWithVowel(text, i, "Chh"))
                'ज' -> sb.append(consonantWithVowel(text, i, "J"))
                'झ' -> sb.append(consonantWithVowel(text, i, "Jh"))
                'ट' -> sb.append(consonantWithVowel(text, i, "T"))
                'ठ' -> sb.append(consonantWithVowel(text, i, "Th"))
                'ड' -> sb.append(consonantWithVowel(text, i, "D"))
                'ढ' -> sb.append(consonantWithVowel(text, i, "Dh"))
                'ण' -> sb.append(consonantWithVowel(text, i, "N"))
                'त' -> sb.append(consonantWithVowel(text, i, "T"))
                'थ' -> sb.append(consonantWithVowel(text, i, "Th"))
                'द' -> sb.append(consonantWithVowel(text, i, "D"))
                'ध' -> sb.append(consonantWithVowel(text, i, "Dh"))
                'न' -> sb.append(consonantWithVowel(text, i, "N"))
                'प' -> sb.append(consonantWithVowel(text, i, "P"))
                'फ' -> sb.append(consonantWithVowel(text, i, "Ph"))
                'ब' -> sb.append(consonantWithVowel(text, i, "B"))
                'भ' -> sb.append(consonantWithVowel(text, i, "Bh"))
                'म' -> sb.append(consonantWithVowel(text, i, "M"))
                'य' -> sb.append(consonantWithVowel(text, i, "Y"))
                'र' -> sb.append(consonantWithVowel(text, i, "R"))
                'ल' -> sb.append(consonantWithVowel(text, i, "L"))
                'व' -> sb.append(consonantWithVowel(text, i, "V"))
                'श' -> sb.append(consonantWithVowel(text, i, "Sh"))
                'ष' -> sb.append(consonantWithVowel(text, i, "Sh"))
                'स' -> sb.append(consonantWithVowel(text, i, "S"))
                'ह' -> sb.append(consonantWithVowel(text, i, "H"))
                'ा' -> sb.append("a")
                'ि' -> sb.append("i")
                'ी' -> sb.append("ee")
                'ु' -> sb.append("u")
                'ू' -> sb.append("oo")
                'ृ' -> sb.append("ri")
                'े' -> sb.append("e")
                'ै' -> sb.append("ai")
                'ो' -> sb.append("o")
                'ौ' -> sb.append("au")
                'ं', 'ँ' -> sb.append("n")
                '्' -> { /* halant suppresses inherent vowel */ }
                in 'a'..'z', in 'A'..'Z', in '0'..'9' -> sb.append(ch)
                else -> {
                    if (Character.isLetterOrDigit(ch)) sb.append(ch)
                }
            }
            i++
        }
        return sb.toString()
    }

    private fun consonantWithVowel(text: String, index: Int, baseConsonant: String): String {
        val next = text.getOrNull(index + 1)
        return if (next != null && (isMatra(next) || next == '्' || next == ' ')) {
            baseConsonant
        } else if (index == text.length - 1) {
            baseConsonant
        } else {
            baseConsonant + "a"
        }
    }

    private fun isMatra(c: Char): Boolean = c in "ािीुूृेैोौंँः"

    /**
     * Normalizes a house number, converting Devanagari numerals (०-९) to Arabic (0-9)
     * and decoding SEC labels like 'बर' -> 'बी', 'सस' -> 'सी'.
     */
    fun decodeHouseNumber(rawHouse: String?): String {
        if (rawHouse.isNullOrBlank()) return ""
        var s = rawHouse.trim()

        // Devanagari digits to ASCII
        val devanagariDigits = "०१२३४५६७८९"
        for (i in 0..9) {
            s = s.replace(devanagariDigits[i], ('0' + i))
        }

        // Replace common SEC encoding letters in house numbers
        s = s.replace("बर", "B")
            .replace("ब", "B")
            .replace("क", "A")
            .replace("सस", "C")
            .replace("च", "C")
            .replace("र", "D")
            .replace("  ", " ")
            .trim()

        return s
    }

    /**
     * Checks if a word is already standard clean Unicode Devanagari (e.g. from Mangal or Tiro fonts).
     * Standard Unicode Devanagari contains vowel signs (matras: \u093E..\u094F) or virama (\u094D)
     * and does NOT contain legacy typewriter phonetic distortions.
     */
    fun isAlreadyUnicodeDevanagari(word: String): Boolean {
        if (word.isBlank()) return false
        val hasMatraOrConjunct = word.any { it in '\u093E'..'\u094F' }
        if (!hasMatraOrConjunct) return false

        val legacySignatures = listOf("पवक", "लसर", "लसह", "रमरर", "लसधल", "मपथपर", "अगवपल", "अगररल", "सपदशरन", "करनपवक")
        return legacySignatures.none { word.contains(it) }
    }

    /**
     * Returns true if text indicates Rajasthan SEC voter list format.
     */
    fun isRajasthanSecText(text: String): Boolean {
        if (text.isBlank()) return false
        val signatures = listOf(
            "photo is",
            "आयप:",
            "आजप:",
            "नगरपपनलकप",
            "नगरपरनलकर",
            "मपग सनखयप",
            "वपरर सनखयप",
            "मकपन सनखयप",
            "मकरन ससखजर",
            "ललग:",
            "नपतप कप",
            "पनत कप",
            "नपतर",
            "नरम:",
            "मतदपतप"
        )
        val lower = text.lowercase(Locale.ROOT)
        return signatures.any { lower.contains(it) }
    }
