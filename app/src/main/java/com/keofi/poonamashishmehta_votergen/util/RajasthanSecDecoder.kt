    /**
     * Converts Rajasthan SEC encoded Devanagari text into clean Hindi Unicode.
     * Implements a universal multi-stage decode engine:
     * Stage 1: Exact dictionary lookup for fast standard matching
     * Stage 2: Substring conjunct normalization (क्ष, ज्ञ, ष्, ष्ट, ह, etc.)
     * Stage 3: Suffix rules (-ानी, -वाल, -ावट, -ा matra, -ी matra)
     * Stage 4: Prefix & mid-token matra rules (प्र-, पुरू-, -ेश, -ो- between consonants)
     */
    fun decodeHindi(text: String?): String {
        if (text.isNullOrBlank()) return ""

        val words = text.trim().split(Regex("\\s+"))
        val decodedWords = words.map { word ->
            decodeWord(word)
        }

        return decodedWords.joinToString(" ")
    }

    private fun decodeWord(word: String): String {
        if (word.isBlank()) return ""

        // 1. Direct dictionary match
        WORD_MAP[word]?.let { return it }

        // 2. If already standard Unicode Devanagari (rendered via Mangal or Tiro font), preserve intact
        if (isAlreadyUnicodeDevanagari(word)) {
            return word
        }

        var res = word

        // 3. High-priority standalone / compound substitutions
        if (res == "लसर" || res == "लसह" || res.endsWith("लसर") || res.endsWith("लसह")) res = res.replace("लसर", "सिंह").replace("लसह", "सिंह")
        if (res == "जसन" || res == "जकन" || res == "जफन") return "जैन"
        if (res == "दववर" || res == "दकवर" || res == "दकरल") return "देवी"
        if (res == "शमपर" || res == "रमरर") return "शर्मा"
        if (res == "अगररल" || res == "अगवपल") return "अग्रवाल"
        if (res == "मरसपर" || res == "मपथपर") return "माथुर"
        if (res == "कचर") return "कौर"
        if (res == "मकपन" || res == "मकरन") return "मकान"
        if (res == "सनखयप" || res == "ससखजर") return "संख्या"
        if (res.contains("करनपवक")) res = res.replace("करनपवक", "करनावट")
        if (res.contains("कनपरवक")) res = res.replace("कनपरवक", "करनावट")
        if (res.contains("सपदशरन")) res = res.replace("सपदशरन", "सुदर्शन")
        if (res.contains("मनप")) res = res.replace("मनप", "मन्नू")
        if (res.contains("अकत")) res = res.replace("अकत", "अक्षत")
        if (res.contains("मकरतप") || res.contains("मकहरर")) res = res.replace("मकरतप", "मेहता").replace("मकहरर", "मेहता")
        if (res.contains("आनशष")) res = res.replace("आनशष", "आशीष")
        if (res.contains("आशरष") || res.contains("आरलष")) res = res.replace("आशरष", "आशीष").replace("आरलष", "आशीष")
        if (res.contains("पपनम") || res.contains("पसनम")) res = res.replace(Regex("प[पस]नम"), "पूनम")
        if (res.contains("लकम")) res = res.replace("लकम", "लक्ष्म")
        if (res.contains("जपन")) res = res.replace("जपन", "ज्ञान")
        if (res.contains("शरव") || res.contains("शलर")) res = res.replace("शरव", "श्री").replace("शलर", "श्री")
        if (res.contains("चचर") || res.contains("चचह")) res = res.replace("चचर", "चौ").replace("चचह", "चौ")
        if (res.contains("गचर")) res = res.replace("गचर", "गौर")
        if (res.contains("जसन") || res.contains("जकन") || res.contains("जफन")) res = res.replace(Regex("ज[सकफ]न"), "जैन")
        if (res.contains("चतपवरदर")) res = res.replace("चतपवरदर", "चतुर्वेदी")
        if (res.contains("चचहपन") || res.contains("चचरपन") || res.contains("चचहरन") || res.contains("चयरपन")) res = res.replace(Regex("च[चयर]ह?पन"), "चौहान")
        if (res.contains("चचधरर") || res.contains("चचधरल") || res.contains("चचधर")) res = res.replace(Regex("चचधर[रल]?"), "चौधरी")
        if (res.contains("खणरवलवपल") || res.contains("खनरकलवपल")) res = res.replace(Regex("ख[णन]र[वक]लवपल"), "खंडेलवाल")

        // 3. Known suffix transforms (evaluated from longest to shortest)
        // -कनपरवक / -करनपवक -> -करनावट
        if ((res.endsWith("कनपरवक") || res.endsWith("करनपवक")) && res.length > 6) {
            res = res.substring(0, res.length - 6) + "करनावट"
        }
        // -करणपवत -> -कर्णावत
        if (res.endsWith("करणपवत") && res.length >= 6) {
            res = res.substring(0, res.length - 6) + "कर्णावत"
        }
        // -लपणपवत -> -राणावत
        if (res.endsWith("लपणपवत") && res.length >= 6) {
            res = res.substring(0, res.length - 6) + "राणावत"
        }
        // -पवक -> -ावट (e.g. करनपवक -> करनावट)
        if (res.endsWith("पवक") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "ावट"
        }
        // -पवत -> -ावत (e.g. रपवत -> रावत, लपणपवत -> राणावत)
        if (res.endsWith("पवत") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "ावत"
        }
        // -वपनर -> -वानी (e.g. लपलवपनर -> लालवानी, दपतवपनर -> दातवानी, रनगवपनर -> डिंगवानी)
        if (res.endsWith("वपनर") && res.length > 4) {
            res = res.substring(0, res.length - 4) + "वानी"
        }
        // -तपनर -> -तानी (e.g. मनगतपनर -> मंगतानी, भगतपनर -> भगतानी)
        if (res.endsWith("तपनर") && res.length > 4) {
            res = res.substring(0, res.length - 4) + "तानी"
        }
        // -पनर -> -ानी (e.g. चनदनपनर -> चंदनानी, गपरनपनर -> गुरनानी, नशचनदपनर -> टेकचंदानी)
        if (res.endsWith("पनर") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "ानी"
        }
        // -वपल -> -वाल (e.g. अगवपल -> अग्रवाल, खणरवलवपल -> खंडेलवाल, बनसरवपल -> बंसीवाल, धपररवपल -> धारीवाल)
        if (res.endsWith("वपल") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "वाल"
        }
        // -पयच -> -ायच (e.g. रनगपयच -> डंगायच)
        if (res.endsWith("पयच") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "ायच"
        }
        // -सपनर / -सयनर -> -सोनी
        if ((res.endsWith("सपनर") || res.endsWith("सयनर")) && res.length >= 4) {
            res = res.substring(0, res.length - 4) + "सोनी"
        }
        // -कपसर -> -कपूर
        if (res.endsWith("कपसर") && res.length >= 4) {
            res = res.substring(0, res.length - 4) + "कपूर"
        }
        // -मपर -> -मार (e.g. कपमपर -> कुमार)
        if (res.endsWith("मपर") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "मार"
        }
        // -मपरर / -मरर -> -मारी (e.g. कपमरर -> कुमारी)
        if (res.endsWith("मपरर") && res.length > 4) {
            res = res.substring(0, res.length - 4) + "मारी"
        } else if (res.endsWith("मरर") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "मारी"
        }
        // -पपल -> -पाल (e.g. नपगपपल -> नागपाल, यशपपल -> यशपाल, ररजपरल -> राज्यपाल)
        if (res.endsWith("पपल") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "पाल"
        }
        // -लतप -> -लता (e.g. कनकलतप -> कनकलता, कपसपमलतप -> कुसुमलता, हकमलतप -> हेमलता)
        if (res.endsWith("लतप") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "लता"
        }
        // -रप / -ड़प / -डप -> -ड़ा preceded by अरय (e.g. अरयरप / अरयड़प -> अरोड़ा)
        if ((res.endsWith("अरयरप") || res.endsWith("अरयड़प") || res.endsWith("अरयडप")) && res.length >= 5) {
            res = res.substring(0, res.length - 5) + "अरोड़ा"
        }
        // -पनप -> -ाना (e.g. खपरपनप -> खुराना)
        if (res.endsWith("पनप") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "ाना"
        }
        // -बर -> -बी (e.g. पनजपबर -> पंजाबी)
        if (res.endsWith("बर") && res.length > 2) {
            res = res.substring(0, res.length - 2) + "बी"
        }
        // -ररक -> -रीक (e.g. पपररक -> पारीक)
        if (res.endsWith("ररक") && res.length > 3) {
            res = res.substring(0, res.length - 3) + "रीक"
        }
        // -ठर -> -ठी (e.g. नतपपठर -> त्रिपाठी, बसरपठर -> बासेठी)
        if (res.endsWith("ठर") && res.length > 2) {
            res = res.substring(0, res.length - 2) + "ठी"
        }
        // -यप -> -या (e.g. भपटरयप -> भाटिया, मपथपरयप -> माथुरिया, मपरनरयप -> मोरिया)
        if (res.endsWith("यप") && res.length > 2) {
            res = res.substring(0, res.length - 2) + "या"
        }
        // Trailing 'प' -> 'ा' (aa ki matra) e.g. कमलप -> कमला, पदमप -> पद्मा, शमपर -> शर्मा, एकतप -> एकता, उमप -> उमा
        if (res.endsWith("प") && res.length > 1 && !res.endsWith("अप")) {
            res = res.substring(0, res.length - 1) + "ा"
        }
        // Trailing 'र' -> 'ी' (ee ki matra) if length > 2 and preceded by consonant
        if (res.endsWith("र") && res.length > 2 && !res.endsWith("पर") && !res.endsWith("कर") && !res.endsWith("मर") && !res.endsWith("वर") && !res.endsWith("दर") && !res.endsWith("तर")) {
            res = res.substring(0, res.length - 1) + "ी"
        }

        // 4. Prefix & Initial Syllable rules
        if (res.startsWith("पकप")) res = "प्रका" + res.substring(3)
        if (res.startsWith("पतर")) res = "प्रती" + res.substring(3)
        if (res.startsWith("पदर")) res = "प्रदी" + res.substring(3)
        if (res.startsWith("पपर") && res.length > 3) res = "पुरू" + res.substring(3)
        if (res.startsWith("सपद")) res = "सुद" + res.substring(3)
        if (res.startsWith("सपध")) res = "सुध" + res.substring(3)
        if (res.startsWith("सपर") && res.length > 3) res = "सुरे" + res.substring(3)
        if (res.startsWith("सपन") && res.length > 3) res = "सुनी" + res.substring(3)
        if (res.startsWith("सपम") && res.length > 3) res = "सुमि" + res.substring(3)
        if (res.startsWith("अनप") && res.length > 3) res = "अनु" + res.substring(3)
        if (res.startsWith("कपम") && res.length > 3) res = "कुमु" + res.substring(3)
        if (res.startsWith("कपस") && res.length > 3) res = "कुसु" + res.substring(3)
        if (res.startsWith("कपण") && res.length > 3) res = "कुणा" + res.substring(3)
        if (res.startsWith("कपन") && res.length > 3) res = "कुंद" + res.substring(3)
        if (res.startsWith("कपल") && res.length > 3) res = "कुल" + res.substring(3)
        if (res.startsWith("वव") && res.length > 2) res = "वि" + res.substring(2)
        if (res.startsWith("नन") && res.length > 2) res = "नि" + res.substring(2)
        if (res.startsWith("दद") && res.length > 2) res = "दी" + res.substring(2)
        if (res.startsWith("दर") && res.length > 2) res = "दी" + res.substring(2)
        if (res.startsWith("वर") && res.length > 2) res = "वी" + res.substring(2)
        if (res.startsWith("सर") && res.length > 2) res = "सी" + res.substring(2)
        if (res.startsWith("अरपत")) res = "अर्पित" + res.substring(4)
        if (res.startsWith("अचरनप")) res = "अर्चना" + res.substring(5)
        if (res.startsWith("अजपरन")) res = "अर्जुन" + res.substring(5)
        if (res.startsWith("अरनवनद")) res = "अरविंद" + res.substring(6)
        if (res.startsWith("अननरद")) res = "अनिरुद्ध" + res.substring(5)

        // 5. -कश / -हश -> -ेश (e.g. रपजकश -> राजेश, रपकहश -> राकेश, ननलकश -> निलेश, कमलकश -> कमलेश, उमहश -> उमेश, दनकपश -> दिनेश)
        if ((res.endsWith("कश") || res.endsWith("हश")) && res.length > 2) {
            res = res.substring(0, res.length - 2) + "ेश"
        }

        // 6. Mid-word character vowel restorations
        val consonant = "[क-ह]"

        // Mid-word 'य' between consonants -> 'ो' (e.g. कयमल -> कोमल, तयमर -> तोमर, अशयक -> अशोक, मनयज -> मनोज, सरयज -> सरोज, मयरन -> मोहन, सयनर -> सोनी)
        val midO = Regex("($consonant)य($consonant)")
        res = midO.replace(res) { mr ->
            mr.groupValues[1] + "ो" + mr.groupValues[2]
        }

        // Mid-word 'प' between consonants -> 'ा' (e.g. मकपन -> मकान, रपम -> राम, दपस -> दास, पपल -> पाल, नपथ -> नाथ, लपल -> लाल, मदपन -> मदान)
        val midAa = Regex("($consonant)प($consonant)")
        res = midAa.replace(res) { mr ->
            mr.groupValues[1] + "ा" + mr.groupValues[2]
        }

        return res
    }

